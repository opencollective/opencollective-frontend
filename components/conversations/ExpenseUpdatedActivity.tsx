import React from 'react';
import { isEqual, isNil, isPlainObject, startCase } from 'lodash-es';
import { FileText, Landmark } from 'lucide-react';
import type { MessageDescriptor } from 'react-intl';
import { defineMessage, defineMessages, FormattedMessage, useIntl } from 'react-intl';

import { LegalDocumentRequestStatus } from '../../lib/graphql/types/v2/graphql';
import { i18nLegalDocumentStatus } from '../../lib/i18n/legal-document';
import i18nPayoutMethodType from '../../lib/i18n/payout-method-type';

/**
 * Payout method as recorded in `COLLECTIVE_EXPENSE_UPDATED` activities. `data` is omitted when
 * the expense never used this payout method (e.g. a replacement for an expense kept on the archived one).
 */
type PayoutMethodSnapshot = {
  id: number;
  type: string;
  name?: string;
  currency?: string;
  isSaved?: boolean;
  data?: Record<string, unknown>;
};

type ExpenseUpdatedActivityData = {
  isSystem?: boolean;
  previousData?: { status?: string; taxFormStatus?: string; payoutMethod?: PayoutMethodSnapshot };
  newData?: { taxFormStatus?: string; payoutMethod?: PayoutMethodSnapshot };
  taxForm?: { year?: number; documentType?: string; requestStatus?: string };
};

const isTaxFormUpdate = (data: ExpenseUpdatedActivityData): boolean =>
  Boolean(data?.newData?.taxFormStatus || data?.previousData?.taxFormStatus || data?.taxForm);

const isPayoutMethodUpdate = (data: ExpenseUpdatedActivityData): boolean =>
  Boolean(data?.newData?.payoutMethod || data?.previousData?.payoutMethod);

/**
 * Whether the activity was generated by the platform (tax form or payout method change) rather than
 * by someone editing the expense. Details are only exposed to users allowed to see them.
 */
export const isSystemExpenseUpdate = (data: ExpenseUpdatedActivityData): boolean =>
  Boolean(data?.isSystem) || isTaxFormUpdate(data) || isPayoutMethodUpdate(data);

const isPayoutMethodReplaced = (data: ExpenseUpdatedActivityData): boolean => {
  const previousId = data?.previousData?.payoutMethod?.id;
  const newId = data?.newData?.payoutMethod?.id;
  return !isNil(previousId) && !isNil(newId) && previousId !== newId;
};

const TaxFormMessages: Partial<Record<LegalDocumentRequestStatus, MessageDescriptor>> = defineMessages({
  [LegalDocumentRequestStatus.REQUESTED]: {
    id: 'Expense.Activity.TaxFormRequested',
    defaultMessage: 'Tax form requested',
  },
  [LegalDocumentRequestStatus.RECEIVED]: {
    id: 'XbazB4',
    defaultMessage: 'Tax form received',
  },
  [LegalDocumentRequestStatus.INVALID]: {
    id: 'TaxForm.Invalidate.Success',
    defaultMessage: 'Tax form invalidated',
  },
});

const TaxFormUpdatedMessage = defineMessage({
  id: 'Expense.Activity.TaxFormUpdated',
  defaultMessage: 'Tax form updated',
});

const PayoutMethodUpdatedMessage = defineMessage({
  id: 'Expense.Activity.PayoutMethodUpdated',
  defaultMessage: 'Payout method updated',
});

const PayoutMethodReplacedMessage = defineMessage({
  id: 'Expense.Activity.PayoutMethodReplaced',
  defaultMessage: 'Payout method replaced',
});

/** Title for system expense updates, `null` to fall back to the generic "Expense updated" */
export const getExpenseUpdatedMessage = (data: ExpenseUpdatedActivityData): MessageDescriptor | null => {
  if (isTaxFormUpdate(data)) {
    return TaxFormMessages[data.newData?.taxFormStatus] || TaxFormUpdatedMessage;
  } else if (isPayoutMethodUpdate(data)) {
    return isPayoutMethodReplaced(data) ? PayoutMethodReplacedMessage : PayoutMethodUpdatedMessage;
  } else {
    return null;
  }
};

export const getExpenseUpdatedIcon = (data: ExpenseUpdatedActivityData) => {
  if (isTaxFormUpdate(data)) {
    return FileText;
  } else if (isPayoutMethodUpdate(data)) {
    return Landmark;
  } else {
    return null;
  }
};

/** Flattens `{ details: { address: { city } } }` into `{ 'details.address.city': value }` */
const flattenObject = (obj: Record<string, unknown>, prefix = ''): Record<string, unknown> =>
  Object.entries(obj || {}).reduce((result, [key, value]) => {
    const path = prefix ? `${prefix}.${key}` : key;
    if (isPlainObject(value)) {
      return { ...result, ...flattenObject(value as Record<string, unknown>, path) };
    } else {
      return { ...result, [path]: value };
    }
  }, {});

const formatValue = (value: unknown): React.ReactNode => {
  if (isNil(value) || value === '') {
    return <span className="italic">–</span>;
  } else if (Array.isArray(value)) {
    return value.join(', ');
  } else {
    return String(value);
  }
};

const getPayoutMethodChanges = (previous: PayoutMethodSnapshot, next: PayoutMethodSnapshot) => {
  const before = { name: previous.name, currency: previous.currency, ...flattenObject(previous.data) };
  const after = { name: next.name, currency: next.currency, ...flattenObject(next.data) };
  const keys = [...new Set([...Object.keys(before), ...Object.keys(after)])];
  return keys
    .filter(key => !isEqual(before[key], after[key]))
    .map(key => ({ key, label: startCase(key.split('.').pop()), before: before[key], after: after[key] }));
};

const TaxFormDetails = ({ data }: { data: ExpenseUpdatedActivityData }) => {
  const intl = useIntl();
  const previousStatus = data.previousData?.taxFormStatus as LegalDocumentRequestStatus;
  const newStatus = data.newData?.taxFormStatus as LegalDocumentRequestStatus;
  if (!previousStatus || !newStatus) {
    return null;
  }

  const values = {
    year: data.taxForm?.year,
    previousStatus: <strong>{i18nLegalDocumentStatus(intl, previousStatus)}</strong>,
    newStatus: <strong>{i18nLegalDocumentStatus(intl, newStatus)}</strong>,
  };

  return (
    <p>
      {values.year ? (
        <FormattedMessage
          id="Expense.Activity.TaxFormStatusChanged.Year"
          defaultMessage="The payee's {year} tax form status changed from {previousStatus} to {newStatus}."
          values={values}
        />
      ) : (
        <FormattedMessage
          id="Expense.Activity.TaxFormStatusChanged"
          defaultMessage="The payee's tax form status changed from {previousStatus} to {newStatus}."
          values={values}
        />
      )}
    </p>
  );
};

const PayoutMethodDetails = ({ data }: { data: ExpenseUpdatedActivityData }) => {
  const intl = useIntl();
  const previous = data.previousData?.payoutMethod;
  const next = data.newData?.payoutMethod;

  // The expense was kept on the archived payout method: its details were not applied to it
  if (next && !next.data && isPayoutMethodReplaced(data)) {
    return (
      <p>
        <FormattedMessage
          id="Expense.Activity.PayoutMethodReplaced.Kept"
          defaultMessage="The payee replaced this payout method ({type}). This expense still uses the previous details."
          values={{ type: i18nPayoutMethodType(intl, previous?.type || next.type) }}
        />
      </p>
    );
  } else if (!previous?.data || !next?.data) {
    return null;
  }

  const changes = getPayoutMethodChanges(previous, next);
  return (
    <div className="flex flex-col gap-1">
      <p>
        {isPayoutMethodReplaced(data) ? (
          <FormattedMessage
            id="Expense.Activity.PayoutMethodReplaced.Moved"
            defaultMessage="The payee updated their payout method ({type}). This expense now uses the new details."
            values={{ type: i18nPayoutMethodType(intl, next.type) }}
          />
        ) : (
          <FormattedMessage
            id="Expense.Activity.PayoutMethodUpdated.Details"
            defaultMessage="The payee updated the payout method used by this expense ({type})."
            values={{ type: i18nPayoutMethodType(intl, next.type) }}
          />
        )}
      </p>
      {changes.length > 0 && (
        <ul className="mt-1 flex flex-col gap-0.5">
          {changes.map(change => (
            <li key={change.key} className="break-all">
              <FormattedMessage
                id="Expense.Activity.PayoutMethodFieldChanged"
                defaultMessage="{field}: {previousValue} → {newValue}"
                values={{
                  field: <span className="font-medium">{change.label}</span>,
                  previousValue: <span className="text-red-700 line-through">{formatValue(change.before)}</span>,
                  newValue: <span className="text-green-700">{formatValue(change.after)}</span>,
                }}
              />
            </li>
          ))}
        </ul>
      )}
    </div>
  );
};

/**
 * Details for system expense updates (tax form or payout method changes). Returns `null` when the
 * current user is not allowed to see them, in which case only the generic "Expense updated" is shown.
 */
export const renderExpenseUpdatedActivityDetails = (data: ExpenseUpdatedActivityData): React.ReactNode => {
  if (isTaxFormUpdate(data)) {
    return <TaxFormDetails data={data} />;
  } else if (isPayoutMethodUpdate(data)) {
    return <PayoutMethodDetails data={data} />;
  } else {
    return null;
  }
};
