import React from 'react';
import { parse as parseCSV } from 'csv-parse/sync';
import { FormattedMessage } from 'react-intl';

import { fetchFromRESTService } from '../lib/api';
import { cn, getWebsiteUrl } from '../lib/utils';

import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from './ui/Table';
import Loading from './Loading';

/** Rows past this limit are not rendered, the user must download the file to see them */
export const CSV_PREVIEW_MAX_ROWS = 500;

/** If the preview rows are not found within this many bytes, we give up and show the fallback */
export const CSV_PREVIEW_MAX_BYTES = 5 * 1024 * 1024;

// The header, the preview rows, and one extra record to know whether the file has more rows
const PREVIEW_RECORDS = CSV_PREVIEW_MAX_ROWS + 2;

const NUMERIC_CELL_REGEX = /^[-+]?\d[\d,.\s]*$/;

/**
 * The access token is only sent to the REST service, and only REST service
 * and uploaded files (served from this website under `/api/files`) are previewed.
 */
const fetchCSVResponse = async (url: string, signal: AbortSignal): Promise<Response> => {
  const parsedUrl = new URL(url, getWebsiteUrl());
  if (process.env.REST_URL && parsedUrl.origin === new URL(process.env.REST_URL).origin) {
    return fetchFromRESTService(parsedUrl.toString(), { signal });
  } else if (parsedUrl.origin === getWebsiteUrl() && parsedUrl.pathname.startsWith('/api/files/')) {
    const response = await fetch(parsedUrl.toString(), { credentials: 'same-origin', signal });
    if (!response.ok) {
      throw new Error(`Failed to fetch file (${response.status})`);
    }
    return response;
  } else {
    throw new Error('Preview not supported for this URL');
  }
};

const parsePreviewRecords = (content: string): string[][] =>
  parseCSV(content, {
    bom: true,
    relaxColumnCount: true,
    relaxQuotes: true,
    skipEmptyLines: true,
    to: PREVIEW_RECORDS,
  });

const toPreview = (records: string[][]) => {
  const [headers = [], ...rows] = records;
  return {
    headers,
    rows: rows.slice(0, CSV_PREVIEW_MAX_ROWS),
    isTruncated: rows.length > CSV_PREVIEW_MAX_ROWS,
  };
};

const countNewlines = (text: string) => {
  let count = 0;
  for (let idx = text.indexOf('\n'); idx !== -1; idx = text.indexOf('\n', idx + 1)) {
    count++;
  }
  return count;
};

/**
 * Reads the response until the preview rows are available, then cancels it so that a large export
 * is neither fully downloaded nor fully generated by the server.
 */
const readCSVPreview = async (response: Response) => {
  if (!response.body) {
    return toPreview(parsePreviewRecords(await response.text()));
  }

  const reader = response.body.getReader();
  const decoder = new TextDecoder();
  let content = '';
  let bytesRead = 0;
  let newlinesCount = 0;
  try {
    while (true) {
      const { done, value } = await reader.read();
      if (done) {
        return toPreview(parsePreviewRecords(content + decoder.decode()));
      }

      const chunk = decoder.decode(value, { stream: true });
      content += chunk;
      bytesRead += value.byteLength;
      newlinesCount += countNewlines(chunk);

      // Quoted values can span several lines, so a line count is only a hint that enough records are available
      if (newlinesCount >= PREVIEW_RECORDS) {
        try {
          const records = parsePreviewRecords(content.slice(0, content.lastIndexOf('\n') + 1));
          if (records.length >= PREVIEW_RECORDS) {
            return toPreview(records);
          }
        } catch {
          // The content may end inside a quoted value, keep reading
        }
      }

      if (bytesRead > CSV_PREVIEW_MAX_BYTES) {
        throw new Error('The preview rows could not be found in the first bytes of the file');
      }
    }
  } finally {
    reader.cancel().catch(() => {});
  }
};

type CSVPreviewProps = {
  url: string;
  /** Rendered instead of the table when the file can't be fetched or parsed */
  renderFallback: () => React.ReactNode;
};

/**
 * Renders a CSV file as a table. Cells are rendered as text, never as HTML.
 */
const CSVPreview = ({ url, renderFallback }: CSVPreviewProps) => {
  const [state, setState] = React.useState<{
    loading: boolean;
    error?: Error;
    data?: ReturnType<typeof toPreview>;
  }>({ loading: true });

  React.useEffect(() => {
    const abortController = new AbortController();
    setState({ loading: true });
    fetchCSVResponse(url, abortController.signal)
      .then(readCSVPreview)
      .then(data => setState({ loading: false, data }))
      .catch(error => {
        if (!abortController.signal.aborted) {
          setState({ loading: false, error });
        }
      });

    return () => abortController.abort();
  }, [url]);

  const numericColumns = React.useMemo(() => {
    if (!state.data) {
      return [];
    }

    return state.data.headers.map((_, columnIdx) => {
      const values = state.data.rows.map(row => row[columnIdx]).filter(Boolean);
      return values.length > 0 && values.every(value => NUMERIC_CELL_REGEX.test(value));
    });
  }, [state.data]);

  if (state.loading) {
    return <Loading />;
  } else if (state.error || !state.data?.headers.length) {
    return renderFallback();
  }

  const { headers, rows, isTruncated } = state.data;
  return (
    <div className="w-full overflow-hidden rounded-xl bg-white shadow-lg" data-cy="csv-preview">
      <Table
        className="max-h-[calc(100dvh-74px-10rem)] rounded-none border-0"
        innerClassName="text-xs"
        data-cy="csv-preview-table"
      >
        <TableHeader className="sticky top-0 z-10 bg-slate-50">
          <TableRow highlightOnHover={false}>
            {headers.map((header, idx) => (
              // eslint-disable-next-line react/no-array-index-key
              <TableHead key={idx} className={cn('h-9 whitespace-nowrap', numericColumns[idx] && 'text-right')}>
                {header}
              </TableHead>
            ))}
          </TableRow>
        </TableHeader>
        <TableBody>
          {rows.map((row, rowIdx) => (
            // eslint-disable-next-line react/no-array-index-key
            <TableRow key={rowIdx}>
              {headers.map((_, columnIdx) => (
                <TableCell
                  // eslint-disable-next-line react/no-array-index-key
                  key={columnIdx}
                  className={cn(
                    'h-auto min-h-0 py-1.5 whitespace-nowrap',
                    numericColumns[columnIdx] && 'text-right tabular-nums',
                  )}
                >
                  {row[columnIdx]}
                </TableCell>
              ))}
            </TableRow>
          ))}
        </TableBody>
      </Table>
      <div className="border-t px-4 py-2 text-xs text-muted-foreground">
        {isTruncated ? (
          <FormattedMessage
            defaultMessage="Showing the first {count} rows. Download the file to see all of them."
            id="MBoUNC"
            values={{ count: rows.length }}
          />
        ) : (
          <FormattedMessage
            defaultMessage="{count, plural, one {# row} other {# rows}}"
            id="fad/lV"
            values={{ count: rows.length }}
          />
        )}
      </div>
    </div>
  );
};

export default CSVPreview;
